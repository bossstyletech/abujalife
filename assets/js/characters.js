// Global Helpers
function getCharacterById(id) {
    return ABUJA_CHARACTERS[id] || ABUJA_CHARACTERS['tunde'];
}

function getCharacterOutfitImage(characterId, outfitKey) {
    const char = getCharacterById(characterId);
    if (!char) return 'assets/img/characters/tunde/Man_standing_in_hoodie_20261005064533.jpg';

    // Map common outfit alias keys
    const aliasMap = {
        'street': 'hoodie',
        'techie': 'hoodie',
        'casual': 'tshirt',
        'traditional': 'agbada',
        'senator': 'kaftan',
        'corporate': 'suit',
        'smart_casual': 'polo',
        'lounge': 'joggers',
        'vip': 'sunglasses'
    };

    const targetKey = aliasMap[outfitKey] || outfitKey;

    let resultPath = '';
    if (char.outfits[targetKey]) {
        resultPath = char.outfits[targetKey];
    } else if (char.outfits['hoodie']) {
        resultPath = char.outfits['hoodie'];
    } else if (char.thumb) {
        resultPath = char.thumb;
    } else {
        const firstKey = Object.keys(char.outfits)[0];
        resultPath = char.outfits[firstKey] || '';
    }

    // Prefer transparent, portrait-cropped PNG version
    return resultPath ? resultPath.replace(/\.jpg$/i, '.png') : '';
}

